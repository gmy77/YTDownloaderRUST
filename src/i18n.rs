//! Testi dell'interfaccia. L'inglese ricalca quello di YoutubeDownloader (Tyrrrz);
//! l'italiano è una traduzione. Nei testi `**parola**` indica il grassetto e
//! `{0}`/`{1}` i valori inseriti a runtime.

use serde::{Deserialize, Serialize};

#[derive(Serialize, Deserialize, Clone, Copy, PartialEq, Debug)]
pub enum Language {
    System,
    English,
    Italian,
}

impl Language {
    pub const ALL: [Language; 3] = [Language::System, Language::English, Language::Italian];

    pub fn name(self) -> &'static str {
        match self {
            Language::System => "System",
            Language::English => "English",
            Language::Italian => "Italiano",
        }
    }

    pub fn strings(self) -> &'static Tr {
        match self {
            Language::English => &EN,
            Language::Italian => &IT,
            Language::System => {
                if system_is_italian() {
                    &IT
                } else {
                    &EN
                }
            }
        }
    }
}

#[cfg(windows)]
fn system_is_italian() -> bool {
    #[link(name = "kernel32")]
    extern "system" {
        fn GetUserDefaultUILanguage() -> u16;
    }
    // Lingua primaria = 10 bit bassi del LANGID; 0x10 è l'italiano.
    unsafe { GetUserDefaultUILanguage() & 0x3ff == 0x10 }
}

#[cfg(not(windows))]
fn system_is_italian() -> bool {
    std::env::var("LANG").map(|l| l.starts_with("it")).unwrap_or(false)
}

/// Sostituisce `{0}`, `{1}`… con gli argomenti.
pub fn fmt(template: &str, args: &[&str]) -> String {
    let mut out = template.to_string();
    for (i, a) in args.iter().enumerate() {
        out = out.replace(&format!("{{{i}}}"), a);
    }
    out
}

